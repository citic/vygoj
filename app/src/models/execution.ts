function serverEncode(text: string) {
  // See https://stackoverflow.com/a/69992416
  return Buffer.from(text, 'utf8').toString('base64');
}

function serverDecode(data: string) {
  // See https://stackoverflow.com/a/69992416
  return Buffer.from(data, 'base64').toString('utf8');
}

/**
 * Controls an execution of the user solution against only one test case. Input:
 * 
 * - The problem object containing test cases, compiler options
 * - The index of the test case to be evaluated from the problem
 * - User solution
 * - Extra proofs (indicated in problem object), eg: minimum number of threads
 * 
 * Output is a promise of an ExecutionResult object that contains:
 * 
 * - The standard output generated by user solution
 * - A verdict of the test case: passed, wrong answer, timeout...
 * - The standard error output
 * - Results of static and dynamic code proofs if asked in problem object
 */
export default class Execution {
  // The programming language used by user to write the code solution
  language: keyof vyg.LanguageDefaults;
  // The problem to be solved
  problem: Problem;
  // Needed?
  message: vyg.Message;
  // Directory where the executable and test cases are stored
  dir: string = '';
  // Executable full path for extra proofs
  executable: string | null = null;
  
  // Constructor
  constructor(problem: Problem, message: vyg.Message) {
    // Language is sent by client, but if omitted, we suppose 'C'
    this.language = (message.language || 'C') as keyof vyg.LanguageDefaults;
    this.problem = problem;
    this.message = message;
  }

  // Runs a test case of the problem given in the constructor
  // This method can be called for each test case of the problem reusing the Execution object
  async run(index: number) {
    // Get the test case to run
    console.assert(index < this.problem.tests.length);
    const test: vyg.TestInterface = this.problem.tests[index];
    // The uri to call the backed using fetch(uri, options)
    // TODO: change wait to false, see https://ce.judge0.com/#submissions
    const uri = `${config.getBackend()}/submissions?base64_encoded=true&wait=true`;
    // The JSON object to be sent in the body of the POST message
    const submission: vyg.Judge0Submission = {
      source_code: this.message.code || '',
      language_id: languageDefaults[this.language].id,
      compiler_options: languageDefaults[this.language].compiler_options,
      stdin: serverEncode(test.input),
      expected_output: serverEncode(test.output),
    };
    // The options of the fetch(uri, options) message
    const options: nodeFetch.RequestInit = {
      method: 'post',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(submission),
    };
    // TODO: log the run in database
    console.log('uri::', uri, 'SUBMISSION::', submission);
    // Return a promise that resolves to an execution result
    //return fetch(uri, options)
    //  .then((response) => { return response.json(); })
    //  .then((json) => { return new Response(json)} );
    // Execute the code in the backend
    const response = await fetch(uri, options);
    // TODO: change DefaultResponse by Judge0Response when using wait=false
    const judge0result = await response.json() as vyg.Judge0Response;
    // TODO: log the result in database
    console.log(judge0result);
    // Convert Judge0 result to Vygoj result
    const testCaseResult = this.convertTo(judge0result);
    // If there futher proofs, execute them
    if (testCaseResult.status === vyg.Status.passed && this.problem.hasProofs()) {
      await this.runProofs(index, testCaseResult);
    }
    // If result passed test cases
    return testCaseResult;
  }

  /*
  const result: vyg.RunResultInterface = {
    totalDuration: 0.420019,
    threadCount: 1,
    outputs: [
      { passed: false, output: 'Hello\n' },
      { passed: true, output: '0' },
      { passed: false, output: 'world!\n' },
    ],
  };
  */
  convertTo(judge0result: vyg.Judge0Response): vyg.TestCaseResult {
    // Get the values to build the response
    let status = vyg.Status.pending;
    const j0status = judge0result.status_id ?? judge0result?.status.id ?? 0;
    console.assert(j0status >= 3);
    if (j0status === 3) {
      status = vyg.Status.passed;
    } else if (j0status === 4) {
      status = vyg.Status.wrong;
    } else if (j0status === 5) {
      status = vyg.Status.timeout;
    } else if (j0status === 6) {
      status = vyg.Status.compilerError;
    } else if (j0status >= 7 && j0status <= 12) {
      status = vyg.Status.runtimeError;
    } else if (j0status >= 13) {
      status = vyg.Status.internalError;
    }

    const result: vyg.TestCaseResult = {
      compileOutput: judge0result.compile_output,
      cpuTime: judge0result.time,
      exitCode: judge0result.exit_code ?? 0,
      memory: judge0result.memory,
      message: judge0result.message,
      status,
      stderr: judge0result.stderr,
      stdout: judge0result.stdout,
      threadCount: 0,
      wallTime: judge0result.wall_time ?? '',
    };
    return result;
  }

  // Judge0 does not provide info about threading. This is a naive post-backend implementation
  // Run the extra proofs for the given solution and store the result in the given object
  async runProofs(index: number, result: vyg.TestCaseResult) {
    try {
      await this.buildExecutable();
      await this.runThreadCountProof(index, result);
    } catch (error) {
      console.error(error);
    }
  }

  // Compiles the user solution and generates an executable, if it is not already compiled
  async buildExecutable() {
    if (this.executable === null) {
      // TODO: use language from message
      const language = 'C';
      const compiler = languageDefaults[language].compiler;
      const options = languageDefaults[language].compiler_options;
      const extension = languageDefaults[language].file_extension;
      // Create a temporary directory to store executable and test cases
      this.dir = await fs.mkdtemp(path.join(os.tmpdir(), 'vyg_'));
      // Copy source code to a file
      // TODO: support for multiple source files
      const source = path.join(this.dir, `main.${extension}`);
      await fs.writeFile(source, serverDecode(this.message.code || ''));
      // Compiler invocation
      const exe = path.join(this.dir, `solution`);
      const cmd = `${compiler} ${options} ${source} -o ${exe}`;
      console.log(cmd);
      const { stdout, stderr } = await exec(cmd, { timeout: 3000 });
      console.log(`compiler stdout: ${stdout}`);
      console.error(`compiler stderr: ${stderr}`);
      // Success
      this.executable = exe;
    }
  }

  // Remove temporary directory and files used by the execution
  async rmDir() {
    if (this.executable) {
      await fs.rm(this.dir, { force: true, recursive: true });
      this.dir = '';
      this.executable = null;
    }
  }

  // Checks that user solution create the required count of threads
  async runThreadCountProof(index: number, result: vyg.TestCaseResult) {
    // Get the test case
    console.assert(index < this.problem.tests.length);
    const test = this.problem.tests[index];
    // Copy stdin to a file
    const stdin = path.join(this.dir, `input${index}.txt`);
    console.log(stdin);
    await fs.writeFile(stdin, test.input);

    // To get the number of created threads, we use GDB: -q quiet, -ex runs a command as if user
    // types it in interactive mode. We count output lines that report New Thread events:
    // gdb -q -ex=r -ex=q --args ./exe | grep 'New Thread' | wc -l
    const exe = this.executable;
    const cmd = `gdb -q '-ex=r < ${stdin}' -ex=q --args ${exe} | grep 'New Thread' | wc -l`;
    console.log(cmd);
    const { stdout, stderr } = await exec(cmd, { timeout: 3000 });
    console.log(stdout);
    console.log(stderr);

    // Standard output must contain the number of created threads
    result.threadCount = parseInt(stdout, 10);
    // Check it is in range
    const inRange = this.problem.minThreads <= result.threadCount &&
      result.threadCount <= this.problem.maxThreads;
    // If user did not create the asked amount of threads
    if (!inRange) {
      // Mark the test case failed
      result.status = vyg.Status.runtimeError;
      // Provide a descriptive message
      result.message = result.message ? `${result.message} ` : '';
      result.message += serverEncode(`Invalid amount of secondary threads (${result.threadCount})`);
    }
  }
}
