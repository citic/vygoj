class Execution:
    """Controls an execution of the user solution against only one or several test cases. Input:

    - The problem object containing test cases, compiler options
    - The index of the test case to be evaluated from the problem, or None for all tests
    - User solution
    - Extra proofs (indicated in problem object), eg: minimum number of threads

    Output is an ExecutionResult object that contains:

    - The standard output generated by user solution
    - A verdict of the test case: passed, wrong answer, timeout...
    - The standard error output
    - Results of static and dynamic code proofs if asked in problem object
    """
    def __init__(self, problem_json, solution_json):
        """ Constructor """
        # The problem to be solved
        self.problem = vyg.Problem('', problem_json)
        # The solution submitted by user
        self.solution = vyg.Message(solution_json)
        # The programming language used by user to write the code solution
        # Language is sent by client, but if omitted, we suppose 'C'
        self.language = self.solution.language or 'C'
        # Directory where the executable and test cases are stored in the container. If empty
        # the /home/student directory is used
        self.dir = ''
        # The filename of the student's solution, e.: 'solution.c'
        self.source_file = ''
        # Executable full path for extra proofs
        self.executable = ''
        # Docker container to compiler and run test cases
        self.container:docker.Container = None
        # The result of all test cases, a dictionary that will be returned to frontend
        #self.result = ExecutionResult()
        self.result = {
            'totalDuration': 0.420019,
            'threadCount': 1,
            'outputs': [
                { 'passed': False, 'output': 'Hello\n' },
                { 'passed': True, 'output': '0' },
                { 'passed': False, 'output': 'world!\n' },
            ],
        }

    def execute(self):
        """ Execute the solution against all test cases """
        try:
            # TODO(jhc): log the run in database
            # Do not run code directly on the OS, isolate student code into a Docker container
            self.create_container()
            # Copy the student solution and test cases to the container
            self.copy_files()
            # If the solution is in a language that should be compiled, compile it
#            self.compile()
            # Run all test cases
#            for index in range(len(self.problem.tests)):
                # Create an execution object, run it, and wait its execution result
#                self.run_test_case(index)
            # Remove Docker container
            self.remove_container()
            # Return the array of results as a JSON string
            return vyg.to_json(self.result)
        except Exception as error:
            # TODO(jhc): Communicate errors to admins, professors, or students
            raise error

    def create_container(self):
        """ Create a Docker container and set it to self.container reference """
        # Create a container and run it but do not wait until it finishes to run the command, the
        # detach=True argument returns immediately. We run 'sleep infinity' to be sure the
        # command will last forever and keep the container running, but not consuming resources.
        # We will use the container to compile the student solution and run against all the test
        # cases defined in the Problem. Therefore we need to run several other commands in the
        # container. This may be not the best approach, but it provides a good balance between
        # security and efficiency. After the student solution is run against all test cases, the
        # container is is removed by the remove_container() method. Many of provided arguments are
        # used to constraint the container in order to run unsecure code coming from users.
        # Doc: https://docker-py.readthedocs.io/en/stable/containers.html
        # TODO(jhc): Run for the amount of seconds indicated by the problem or default for language
        # TODO(jhc): More arguments: auto_remove=True, hostname=<str>, isolation=<str>,
        # kernel_memory=<int|str>, log_config, mem_reservation=<int|str>, memswap_limit=<int|str>,
        # name=<str>, nano_cpus=<int>, security_opt=<list>, stop_signal=<str>, sysctls=<dict>,
        # ulimits=<list>
        self.container = docker_client.containers.run(
            # Image can be created running the Makefile inside the engine/ subfolder
            image='debian-dev:latest',
            # Do not wait until the command finishes, just return the reference to the container
            detach=True,
            # A dummy command to start the container
            command='sleep infinity',
            # TODO(jhc): Limit memory from the Problem configuration
            mem_limit='512m',
            # TODO(jhc): Support the distributed programming paradigm
            network_disabled=True,
            # Student solutions do not have root privileges
            privileged=False,
            # The root filesystem is read-only. Students can only write on /home/student or /tmp
            read_only=True,
            # Enable to run linux-perf without root privileges in current session
            #sysctls={'kernel.perf_event_paranoid': 1},
            # Simulate a terminal to capture stdout and stderr
            tty=True,
            # Log in as the student user
            user='student')

    def remove_container(self):
        """ Stop the container if it is running and destroy it """
        assert self.container
        # Stop the execution of the container
        self.container.stop()
        # Remove the container, we force to remove it if stopping failed
        self.container.remove(force=True)
        self.container = None

    def copy_files(self):
        """ Copy the student solution and test cases to the container """
        # Docker do not allow to copy individual files from host to container. Wee need to
        # prepare a temp directory on host to store the files, compress them to a tar file, ask
        # Docker to extract the tar file in the container, and finally, remove the temp dir.
        tmp_dir = tempfile.TemporaryDirectory()
        print('---temp_dir', tmp_dir)
        assert self.solution.language in languageDefaults
        flags = languageDefaults[self.solution.language]
        # Copy student solution from JSON object to a file on temporary directory
        self.source_file = f'solution.{flags.file_extension}'
        with open(os.path.join(tmp_dir.name, self.source_file), 'w', encoding='utf8') as file:
            file.write(vyg.decode(self.solution.code))
        # Copy input files of all test cases to the temporary directory
        for index, test in enumerate(self.problem.tests):
            input_file = f'input{index:03}.txt'
            with open(os.path.join(tmp_dir.name, input_file,), 'w', encoding='utf8') as file:
                file.write(vyg.decode(test.input))
        # Compress the temporary directory to a tar file in memory
        mem_tar = io.BytesIO()
        with tarfile.open(fileobj=mem_tar, mode='w|gz') as tar_file:
            tar_file.add(tmp_dir, arcname=os.path.basename(tmp_dir.name))
        mem_tar.seek(0)
        # Extract the tar file in the container
        self.container.put_archive(path='/home/student', data=mem_tar)
        # Remove temporary folder
        #os.rmdir(tmp_dir)

    def run_in_container(self, command, timeout):
        """
        Executes a command in a Docker container and returns stdout, stderr, and exit code.

        Args:
            command: Command to run (str or list)
            timeout: Maximum allowed duration in milliseconds
        
        Returns:
            tuple: (stdout, stderr, exit_code)

        Adapted from DeepSeek
        """
        # TODO(jhc): Use or remove timeout parameter
        # Execute the command, demux separates stdout and stderr into an array result.output[]
        # TODO(jhc): stdin=True?,tty=True,stream=<bool>,workdir=<str>
        # Doc: https://docker-py.readthedocs.io/en/stable/containers.html
        result = self.container.exec_run(cmd=command, stdout=True, stderr=True, demux=True,
                user='student')
        # Decode stdout and stderr (if they exist)
        stdout = result.output[0].decode('utf-8').strip() if result.output[0] else ''
        stderr = result.output[1].decode('utf-8').strip() if result.output[1] else ''
        return stdout, stderr, result.exit_code

