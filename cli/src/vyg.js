#!/usr/bin/env node

import { Command } from 'commander';
import Decoder from './Decoder.js';

class Vyg {
  constructor() {
    this.args = new Command();
  }

  static main() {
    try {
      const vyg = new Vyg();
      vyg.run();
    } catch (error) {
      console.error(error);
    }
  }

  run() {
    this.analyzeArguments();
  }

  analyzeArguments() {
    // General program information
    this.args.name('vyg')
      .description('Vygoj command-line tool')
      .version('v1.0.0');

    // Command to manage vygoj app logs
    this.args.command('decode')
      .description('Decodes Vygoj log')
      .argument('<log.tsv>', 'Tabulator-separated values log file generated by web app')
      .action((filename) => { new Decoder().decode(filename); });

    // Analyze the provided arguments
    this.args.parse();
  }
}

Vyg.main();
